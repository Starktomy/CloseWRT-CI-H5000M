"""让 LuCI 的 clean/compile/install 使用本次交叉编译并校验的固件后端。"""

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", required=True, type=Path)
    parser.add_argument("--binary", required=True, type=Path)
    parser.add_argument("--install", required=True, choices=[
        "/usr/sbin/h5000m-fancontrol", "/usr/bin/at-webserver-rust",
    ])
    args = parser.parse_args()
    binary = args.binary.resolve(strict=True)
    makefile = args.package / "src/Makefile"
    original = makefile.read_text()
    if "H5000M_CI_PREBUILT" not in original:
        makefile.with_name("Makefile.upstream").write_text(original)
    destination = Path(args.install)
    # OpenWrt 的包构建目录会复制 src/，后端保存在源码树外层，clean 不会删掉它。
    makefile.write_text(
        "# H5000M_CI_PREBUILT: generated by install_prebuilt.py\n"
        f"CI_BINARY := {binary}\n"
        ".PHONY: all clean compile install\n"
        "all: compile\n"
        "clean:\n\t@:\n"
        "compile:\n"
        '\ttest -x "$(CI_BINARY)"\n'
        '\tfile "$(CI_BINARY)" | grep -Eq "ELF 64-bit.*ARM aarch64.*(statically linked|static-pie linked)"\n'
        "install: compile\n"
        f'\tinstall -d "$(DESTDIR){destination.parent}"\n'
        f'\tinstall -m0755 "$(CI_BINARY)" "$(DESTDIR){destination}"\n'
    )


if __name__ == "__main__":
    main()
